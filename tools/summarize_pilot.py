"""Summarize the branch pilot by branch point (20k / 40k / 60k frames).

Per arm: initial performance (eval of the branch-point snapshot: runs/branch40k/eval_s{20,40,60}/eval_start.json),
evals at +10k / +20k frames, final return (last eval), eval AUC (trapezoid over start, +10k, +20k, divided by 20k
frames = mean eval return over the window), loss vs the full-update arm(s) of the same branch point, WM / AC update
counts, update seconds per epoch, peak GPU memory (logged per epoch since 2026-10-24 22:3x; older arms: not logged),
mean training-episode return, and implementation notes (strict_off vs the old wm_off weight-decay shrink).

  python3 summarize_pilot.py            -> prints and writes results/pilot_summary.md
"""
import json
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
RUNS = os.path.join(HERE, "..", "runs", "branch40k")
REF = "/home/yeho/RL/ncrl_runs/branch_qw40k/full1024"
OUT = os.path.join(HERE, "..", "results", "pilot_summary.md")
FULL_ARMS = {"R1_full1024", "full_rep", "full_to60k", "s20_full", "s60_full"}


def read_arm(path, max_epochs=20):
    rows = [json.loads(l) for l in open(os.path.join(path, "branch_log.jsonl"))]
    start = next(r for r in rows if r["kind"] == "start")
    e0 = start["epoch"]
    ep = [r for r in rows if r["kind"] == "epoch" and r["epoch"] <= e0 + max_epochs]
    ev = {r["global_frame"]: r["eval/avg_episode_reward"] for r in rows
          if r["kind"] == "eval" and r["epoch"] <= e0 + max_epochs}
    um = os.path.join(path, "update_metrics.jsonl")
    lines = [json.loads(l) for l in open(um)] if os.path.exists(um) else []
    peaks = [l["peak_alloc_GiB"] for l in lines if "peak_alloc_GiB" in l]
    peaks_r = [l["peak_reserved_GiB"] for l in lines if "peak_reserved_GiB" in l]
    args = json.load(open(os.path.join(path, "selective_args.json"))) if os.path.exists(os.path.join(path, "selective_args.json")) else {}
    end = json.load(open(os.path.join(path, "selective_end.json"))) if os.path.exists(os.path.join(path, "selective_end.json")) else {}
    done = any(r["kind"] == "end" for r in rows)
    return dict(start_frame=start["global_frame"], epochs=len(ep), evals=ev, done=done, args=args, end=end,
                update_s=statistics.mean(r["update_s"] for r in ep) if ep else None,
                train_return=statistics.mean(r["train_return"] for r in ep) if ep else None,
                wm=(lines[-1]["wm_steps"], lines[-1]["updates"]) if lines else None,
                peak_alloc=max(peaks) if peaks else None, peak_reserved=max(peaks_r) if peaks_r else None)


def start_eval(frame):
    p = os.path.join(RUNS, f"eval_s{frame // 1000}", "eval_start.json")
    return json.load(open(p)) if os.path.exists(p) else None


def note(name, a):
    n = []
    if a["args"].get("strict_off"):
        n.append("strict off: WM bit-identical")
    elif a["args"].get("wm_every") == 0:
        ch = a["end"].get("rel_change_gru")
        n.append(f"old off: WM shrank {100 * ch:.2f}% (reward-step weight decay)" if ch else "old off (weight decay)")
    if a["args"].get("freeze"):
        n.append("freeze " + ",".join(a["args"]["freeze"])) if not a["args"].get("strict_off") else None
    if a["args"].get("save_end_state"):
        n.append("saved end state (60k branch point)")
    if name == "R1_full1024":
        n.append("ncrl_probe/branch_ncrl.py, before branch_selective")
    if a["peak_alloc"] is None:
        n.append("peak VRAM not logged")
    return "; ".join(n)


def fmt(x, f="{:.0f}"):
    return "—" if x is None else f.format(x)


def main():
    arms = {}
    if os.path.exists(os.path.join(REF, "branch_log.jsonl")):
        arms["R1_full1024"] = read_arm(REF)
    for name in sorted(os.listdir(RUNS)):
        p = os.path.join(RUNS, name)
        if os.path.isdir(p) and os.path.exists(os.path.join(p, "branch_log.jsonl")) and name != "smoke":
            arms[name] = read_arm(p)
    lines = ["# Branch pilot summary (auto-generated by tools/summarize_pilot.py)", "",
             "Quadruped Walk, one base run (seed 1), branch seed 7, 20 epochs (= +20k frames, 2500 AC updates) per arm. "
             "Eval = 10 episodes, mean action, eval env seed 11. 1 seed -> descriptive only.", ""]
    for bp in sorted({a["start_frame"] for a in arms.values()}):
        se = start_eval(bp)
        init = se["avg_episode_reward"] if se else None
        group = {k: v for k, v in arms.items() if v["start_frame"] == bp}
        fulls = [v for k, v in group.items() if k in FULL_ARMS and v["done"]]
        lines.append(f"## Branch at {bp // 1000}k frames — initial performance: "
                     f"{fmt(init)}" + (f" ± {se['se']:.0f} (SE, 10 ep)" if se and se.get('se') else " (not measured yet)"))
        lines += ["", "| arm | WM / AC updates | update s/epoch | peak VRAM GiB (alloc/reserved) | eval +10k | eval +20k (final) | "
                  "eval AUC | final − full mean | train return | notes |", "|---|---|---:|---|---:|---:|---:|---:|---:|---|"]
        full_final = statistics.mean(v["evals"][max(v["evals"])] for v in fulls if v["evals"]) if fulls and all(v["evals"] for v in fulls) else None
        for name, a in group.items():
            f1, f2 = bp + 10000, bp + 20000
            e1, e2 = a["evals"].get(f1), a["evals"].get(f2)
            auc = ((init + e1) / 2 + (e1 + e2) / 2) / 2 if None not in (init, e1, e2) else None
            diff = e2 - full_final if (e2 is not None and full_final is not None and name not in FULL_ARMS) else None
            wm = f"{a['wm'][0]} / {a['wm'][1]}" if a["wm"] else ("all / 2500" if name == "R1_full1024" else "—")
            pk = f"{a['peak_alloc']:.2f} / {a['peak_reserved']:.2f}" if a["peak_alloc"] is not None else "—"
            lines.append(f"| {name}{'' if a['done'] else ' (running)'} | {wm} | {fmt(a['update_s'])} | {pk} | {fmt(e1)} | "
                         f"{fmt(e2)} | {fmt(auc)} | {fmt(diff, '{:+.0f}')} | {fmt(a['train_return'])} | {note(name, a)} |")
        if len(fulls) >= 2:
            fins = [v["evals"].get(bp + 20000) for v in fulls]
            mids = [v["evals"].get(bp + 10000) for v in fulls]
            lines.append(f"\nFull-update replicates at this point: +10k {[round(x) for x in mids if x]}, "
                         f"+20k {[round(x) for x in fins if x]} (spread = same-setting noise)")
        lines.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
