"""Full vs WM 1/4 vs WM 1/8 vs WM OFF: eval return, eval AUC, update time, performance loss, per branch point.

Reads the arms in runs/branch40k (+ the R1 reference) via summarize_pilot.read_arm and the branch-point start evals.
Full reference at a branch point = mean of its full-update arms (40k: R1, full_rep, full_to60k; 20k: s20_full;
60k: s60_full); the range of the 40k full replicates is reported as the same-setting spread.
Writes results/freq_comparison.md and docs/figures/freq_comparison.png.

  python3 compare_freq.py        (figure needs matplotlib: run with the ncrl_env python)
"""
import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import summarize_pilot as S  # noqa: E402

ROOT = os.path.join(HERE, "..")
ARMS = {  # branch point -> {variant: [arm names]}
    20000: {"Full": ["s20_full"], "Every4": ["s20_wm_every4"], "Every8": [], "OFF": ["s20_wm_off"]},
    40000: {"Full": ["R1_full1024", "full_rep", "full_to60k"], "Every4": ["wm_every4"], "Every8": ["wm_every8"],
            "OFF": ["wm_off"]},
    60000: {"Full": ["s60_full"], "Every4": [], "Every8": [], "OFF": ["s60_wm_off"]},
}
FRACTION = {"Full": "1", "Every4": "1/4", "Every8": "1/8", "OFF": "0"}


def load():
    arms = {}
    if os.path.exists(os.path.join(S.REF, "branch_log.jsonl")):
        arms["R1_full1024"] = S.read_arm(S.REF)
    for name in os.listdir(S.RUNS):
        p = os.path.join(S.RUNS, name)
        if os.path.isdir(p) and os.path.exists(os.path.join(p, "branch_log.jsonl")):
            arms[name] = S.read_arm(p)
    return arms


def metrics(a, bp, init):
    e1, e2 = a["evals"].get(bp + 10000), a["evals"].get(bp + 20000)
    auc = ((init + e1) / 2 + (e1 + e2) / 2) / 2 if None not in (init, e1, e2) else None
    rows = [json.loads(l) for l in open(os.path.join(a["path"], "branch_log.jsonl"))]
    e0 = next(r for r in rows if r["kind"] == "start")["epoch"]
    upd_h = sum(r["update_s"] for r in rows if r["kind"] == "epoch" and r["epoch"] <= e0 + 20) / 3600  # first 20 epochs
    return dict(e1=e1, e2=e2, auc=auc, upd=a["update_s"], upd_h=upd_h, done=a["done"], wm=a["wm"],
                peak=a["peak_alloc"], strict=a["args"].get("strict_off", False),
                old_off=a["args"].get("wm_every") == 0 and not a["args"].get("strict_off"))


def main():
    arms = load()
    for k in arms:
        arms[k]["path"] = S.REF if k == "R1_full1024" else os.path.join(S.RUNS, k)
    rows, fig_data = [], {}
    lines = ["# Full vs WM 1/4 vs WM 1/8 vs WM OFF (auto-generated by tools/compare_freq.py)", "",
             "Quadruped Walk, base run seed 1, branch seed 7, +20k frames per arm (2500 actor-critic updates; only the "
             "number of WM gradient steps differs). Eval = 10 episodes, mean action, no guidance. AUC = trapezoid over "
             "(initial, +10k, +20k) / 20k frames. Loss = arm − Full mean. **1 seed: descriptive only.**", ""]
    for bp, variants in ARMS.items():
        se = S.start_eval(bp)
        init = se["avg_episode_reward"] if se else None
        full = [metrics(arms[n], bp, init) for n in variants["Full"] if n in arms and arms[n]["done"]]
        if not full:
            continue
        f_e2 = statistics.mean(m["e2"] for m in full)
        f_auc = statistics.mean(m["auc"] for m in full)
        f_upd = statistics.mean(m["upd"] for m in full)
        lines += [f"## Branch at {bp // 1000}k frames (initial eval {init:.0f} ± {se['se']:.0f})", "",
                  "| variant | WM updates | eval +10k | eval +20k | AUC | loss +20k | loss AUC | update s/epoch | "
                  "update time vs Full | update GPU-h (20 epochs) | peak VRAM alloc |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        fig_data[bp] = {}
        for v, names in variants.items():
            ms = [metrics(arms[n], bp, init) for n in names if n in arms]
            if not ms:
                lines.append(f"| {v} | {FRACTION[v]} | not run | | | | | | | | |")
                continue
            if any(not m["done"] for m in ms):
                lines.append(f"| {v} | {FRACTION[v]} | running | | | | | | | | |")
                continue
            e1 = statistics.mean(m["e1"] for m in ms); e2 = statistics.mean(m["e2"] for m in ms)
            auc = statistics.mean(m["auc"] for m in ms); upd = statistics.mean(m["upd"] for m in ms)
            uh = statistics.mean(m["upd_h"] for m in ms)
            pk = [m["peak"] for m in ms if m["peak"] is not None]
            tag = v + (" ×%d (%s)" % (len(ms), " / ".join(f"{m['e2']:.0f}" for m in ms)) if len(ms) > 1 else "")
            tag += " †" if any(m["old_off"] for m in ms) else (" (strict)" if any(m["strict"] for m in ms) else "")
            loss2 = "—" if v == "Full" else f"{e2 - f_e2:+.0f}"
            lossa = "—" if v == "Full" else f"{auc - f_auc:+.0f}"
            lines.append(f"| {tag} | {FRACTION[v]} | {e1:.0f} | {e2:.0f} | {auc:.0f} | {loss2} | {lossa} | {upd:.0f} | "
                         f"{(upd / f_upd - 1) * 100:+.0f}% | {uh:.2f} | {('%.2f GiB' % max(pk)) if pk else '—'} |")
            fig_data[bp][v] = dict(e2=e2, auc=auc, upd=upd, all_e2=[m["e2"] for m in ms])
        nxt = S.start_eval(bp + 20000)
        if nxt and bp == 20000:  # the base run itself continued from this 20k state with the original update
            alt = [f_e2, nxt["avg_episode_reward"]]
            fig_data[bp]["Full"]["extra"] = [nxt["avg_episode_reward"]]
            lines.append(f"\nExtra Full replicate: the base run's own continuation from the same {bp // 1000}k state (original "
                         f"update, base-run RNG), evaluated at {(bp + 20000) // 1000}k with the same protocol "
                         f"(eval_s{(bp + 20000) // 1000}) = {nxt['avg_episode_reward']:.0f}. Full at +20k then spans "
                         f"{min(alt):.0f}–{max(alt):.0f}; loss vs their mean ({statistics.mean(alt):.0f}): " +
                         ", ".join(f"{v} {fig_data[bp][v]['e2'] - statistics.mean(alt):+.0f}" for v in ("Every4", "Every8", "OFF")
                                   if v in fig_data[bp]) + ". (No +10k eval with this protocol, so not in AUC.)")
        if len(full) > 1:
            lines.append(f"\nFull replicates at +20k: {[round(m['e2']) for m in full]} -> spread "
                         f"{max(m['e2'] for m in full) - min(m['e2'] for m in full):.0f} (same snapshot, same seed).")
        lines.append("")
    lines += ["† 40k WM OFF ran before `--strict_off`: no WM gradient step, but NCRL's reward-head step weight-decayed "
              "the WM (−0.25% over 2500 updates). The 20k/60k OFF arms are strict (WM change exactly 0.0).", "",
              "Update time is the CUDA-synchronized time of the 125 updates per epoch (env collection ~4 s/epoch and "
              "evaluation are excluded). Peak VRAM was logged only for arms started after 2026-10-24 22:3x."]
    out = os.path.join(ROOT, "results", "freq_comparison.md")
    open(out, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))
    try:
        figure(fig_data)
    except ImportError as e:
        print("figure skipped:", e)


def figure(d):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import make_figures as F
    order = ["Full", "Every4", "Every8", "OFF"]
    colors = {20000: F.C1, 40000: F.C2, 60000: F.C3}
    fig, axes = plt.subplots(1, 2, figsize=(9.6, 3.8))
    def connect(ax, xs, ys, c, lab):
        ax.scatter(xs, ys, s=40, color=c, edgecolor=F.SURF, linewidth=2, zorder=3, label=lab)
        for (x0, y0), (x1, y1) in zip(zip(xs, ys), zip(xs[1:], ys[1:])):
            if x1 - x0 == 1:  # only adjacent measured conditions are joined (no line through unmeasured ones)
                ax.plot([x0, x1], [y0, y1], color=c, lw=2, zorder=2)
    for bp, vs in d.items():
        xs = [i for i, v in enumerate(order) if v in vs]
        lab = f"branch at {bp // 1000}k"
        connect(axes[0], xs, [vs[order[i]]["e2"] for i in xs], colors[bp], lab)
        rng = list(vs["Full"]["all_e2"]) + (vs["Full"].get("extra") or [])
        if len(rng) > 1:
            axes[0].vlines(0, min(rng), max(rng), color=colors[bp], lw=1.2, zorder=1)
        connect(axes[1], xs, [vs[order[i]]["upd"] for i in xs], colors[bp], lab)
    fig.text(0.01, 0.01, "Vertical bar at Full = spread of full-update replicates (40k: 3 branch runs; 20k: branch run + "
             "base-run continuation). Points are joined only between adjacent measured conditions.", fontsize=7.5,
             color=F.INK2)
    for ax, t, yl in [(axes[0], "eval return at +20k frames", "eval return (10 episodes)"),
                      (axes[1], "update time", "update seconds per epoch")]:
        ax.set_xticks(range(4), ["Full", "1/4", "1/8", "OFF"])
        ax.set_xlabel("WM gradient steps (fraction of updates)")
        ax.set_ylabel(yl); ax.set_title(t, loc="left", fontsize=10)
        F.style(ax, "y")
    h, l = axes[0].get_legend_handles_labels()
    fig.legend(h, l, loc="lower center", ncol=3, fontsize=8.5, bbox_to_anchor=(0.5, 0.05))
    fig.suptitle("Quadruped Walk branch pilot (1 seed): fewer WM updates vs return and time", x=0.01, ha="left",
                 fontsize=10.5, color=F.INK)
    fig.tight_layout(rect=(0, 0.12, 1, 0.94))
    fig.savefig(os.path.join(ROOT, "docs", "figures", "freq_comparison.png"), dpi=160)
    plt.close(fig)


if __name__ == "__main__":
    main()
